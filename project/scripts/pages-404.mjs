// Runs after `vite build` (see package.json). Makes unknown URLs return a real 404 on Cloudflare Pages.
//
// Pages serves a single-page app in one of two ways:
//   - with a catch-all rule (`/* /index.html 200`): every URL answers 200, even ones that don't exist.
//   - with a 404.html and no catch-all: unmatched URLs get 404.html with status 404.
// This script does the second: it writes one rewrite rule per real page (so deep links still work)
// and copies the app to 404.html (the app then shows its own "Page not found" view).
//
// The list of real pages comes from the code itself, so it can't drift:
//   - static routes from src/App.tsx
//   - /solutions/:type   from the SOLUTIONS keys in src/pages/SolutionDetail.tsx
//   - /industries/:niche from the English industryData keys in src/i18n/pages.ts
//   - /templates/:id     from the templates keys in src/pages/TemplatePage.tsx
// If App.tsx gains a dynamic route this script doesn't know, the build fails instead of 404ing real pages.
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';

const read = (path) => readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
const fail = (message) => {
  console.error(`pages-404: ${message}`);
  process.exit(1);
};

/** The text of the `{ ... }` block that starts at the first `{` after `marker`. */
function block(source, marker, from = 0) {
  const at = source.indexOf(marker, from);
  if (at < 0) fail(`can't find "${marker}"`);
  // A marker ending in '{' points at its own brace (used to skip a type annotation before the value).
  const open = marker.endsWith('{') ? at + marker.length - 1 : source.indexOf('{', at + marker.length);
  let depth = 0;
  for (let i = open; i < source.length; i++) {
    if (source[i] === '{') depth++;
    if (source[i] === '}' && --depth === 0) return source.slice(open + 1, i);
  }
  fail(`unclosed block after "${marker}"`);
}

/** Keys of an object literal at its own top level (nested keys are skipped). */
function topKeys(body) {
  const keys = [];
  let depth = 0;
  for (const line of body.split('\n')) {
    if (depth === 0) {
      const m = line.match(/^\s*['"]?([\w-]+)['"]?\s*:/);
      if (m) keys.push(m[1]);
    }
    for (const ch of line) {
      if (ch === '{' || ch === '[') depth++;
      if (ch === '}' || ch === ']') depth--;
    }
  }
  return keys;
}

const app = read('src/App.tsx');
const routePaths = [...app.matchAll(/<Route\s+path="([^"]+)"/g)].map((m) => m[1]);

const dynamic = {
  '/solutions/:type': () => {
    const source = read('src/pages/SolutionDetail.tsx');
    // SOLUTIONS has a type annotation (`Record<string, { ... }>`), so start at its value, after `= {`.
    return topKeys(block(source, '= {', source.indexOf('const SOLUTIONS')));
  },
  '/industries/:niche': () => topKeys(block(read('src/i18n/pages.ts'), 'industryData:')),
  '/templates/:id': () => topKeys(block(read('src/pages/TemplatePage.tsx'), 'const templates')),
};

const paths = [];
for (const route of routePaths) {
  if (route === '*') continue;
  if (!route.includes(':')) {
    paths.push(route);
    continue;
  }
  const keysFor = dynamic[route];
  if (!keysFor) fail(`App.tsx has the route ${route}, but this script doesn't know its ids. Add it to "dynamic".`);
  const keys = keysFor();
  if (keys.length === 0) fail(`found no ids for ${route}`);
  const prefix = route.slice(0, route.indexOf(':'));
  for (const key of keys) paths.push(prefix + key);
}

// Keep the project's own non-catch-all rules (e.g. /transak-session) first.
const own = read('public/_redirects')
  .split('\n')
  .map((line) => line.trim())
  .filter((line) => line && !line.startsWith('#') && !/^\/\*\s/.test(line));

// Rewrite to "/", not "/index.html": Pages answers /index.html with a redirect that strips it.
// A trailing slash (/pricing/) redirects to the real URL, so links written that way keep working.
const rules = [...new Set(paths)]
  .filter((path) => path !== '/')
  .flatMap((path) => [`${path}/ ${path} 301`, `${path} / 200`]);
if (rules.length > 1900) fail(`${rules.length} rules is too close to the Cloudflare Pages limit of 2000`);

writeFileSync(
  'dist/_redirects',
  ['# Generated by scripts/pages-404.mjs. Edit public/_redirects for your own rules.', ...own, ...rules, ''].join('\n'),
);
copyFileSync('dist/index.html', 'dist/404.html');
console.log(`pages-404: ${paths.length} known pages, ${rules.length} rewrite rules, 404.html written`);
